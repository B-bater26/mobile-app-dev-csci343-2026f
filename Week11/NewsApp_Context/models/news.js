class News {
  constructor(id, category, headline, date, author, agency, desc, imageUrl) {
    this.id = id;
    this.category = category;
    this.headline = headline;
    this.date = date;
    this.author = author;
    this.agency = agency;
    this.desc = desc;
    this.imageUrl = imageUrl;
  }
}

export default News;
